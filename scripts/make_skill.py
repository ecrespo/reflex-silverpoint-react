"""Write the `reflex-silverpoint` skill (silverpoint T-246) from its templates and `reflex-catalog.json`.

The prose is hand-written, in `skills/reflex-silverpoint/templates/`. A template holds `{{version}}`
(this package's), `{{wraps}}` (the silverpoint version) and `<!-- generated:<block> -->` markers;
the generated tables are written between `<!-- generated:<block> -->` and `<!-- /generated:<block> -->`,
and an unknown block fails. Names, props and their types come from the catalog; summaries from the
package's own docstrings; each chart's example from the demo app's datasets and accessor props. Every
`python` block is formatted with ruff, so pre-commit leaves the output as it is.

    uv run python scripts/make_skill.py            # writes skills/reflex-silverpoint/
    uv run python scripts/make_skill.py --check    # fails when the committed skill is stale
"""

import inspect
import json
import re
import subprocess
import sys
from collections.abc import Callable
from pathlib import Path
from typing import Any

import reflex_silverpoint_react as sp

ROOT = Path(__file__).resolve().parent.parent
SKILL = ROOT / "skills" / "reflex-silverpoint"
TEMPLATES = SKILL / "templates"
CATALOG = ROOT / "reflex-catalog.json"
DEMO = ROOT / "silverpoint_react_demo"

GENERATED = (
    "Generated by scripts/make_skill.py from skills/reflex-silverpoint/templates and reflex-catalog.json. "
    "Do not edit: run `uv run python scripts/make_skill.py`."
)

#: References written from a template of the same name.
REFERENCES = ("components", "overlays", "timeline", "dashboard", "palettes", "state-and-events")

#: Component slugs each reference documents; the rest are in components.md.
OVERLAYS = ("modal", "drawer", "popover", "tooltip", "select", "dropdown-menu", "toast", "toaster")
OWN_PAGE = {"dashboard": "dashboard.md", "timeline": "timeline.md", **{s: "overlays.md" for s in OVERLAYS}}

#: Fences that hold no code to run.
PROSE = {"sh", "text", "json"}

#: Charts the demo feeds from props rather than rows.
_SCALAR = {"gauge-arc": {"caption": "Capacity used"}, "meter-chart": {"caption": "Load"}}
#: Accessor props too long for an example (the network's node list).
_LEFT_OUT = {"nodes"}


# ── Helpers ─────────────────────────────────────────────────────────────────────────────


def family_slug(title: str) -> str:
    """`Points & grids` → `points-grids`, silverpoint's family slugs."""
    return re.sub(r"[^a-z]+", "-", title.lower()).strip("-")


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def _code(text: str) -> str:
    return f"`{_cell(text)}`"


def _summary(obj: Any) -> str:
    doc = inspect.getdoc(obj) or ""
    return doc.split("\n\n")[0].replace("\n", " ").strip()


def _props_table(props: list[dict[str, str]]) -> list[str]:
    if not props:
        return ["No props of its own."]
    rows = ["| Python | JS | Type |", "|---|---|---|"]
    rows += [f"| {_code(p['name'])} | {_code(p['js'])} | {_code(p['type'])} |" for p in props]
    return rows


def _demo() -> tuple[dict[str, list[dict[str, Any]]], dict[str, dict[str, Any]]]:
    """The demo app's datasets (by slug) and the accessor props it reads them with."""
    sys.path.insert(0, str(DEMO))
    try:
        from silverpoint_react_demo.data_tools import initial_datasets
        from silverpoint_react_demo.datasets import KEY_PROPS
    finally:
        sys.path.remove(str(DEMO))
    return initial_datasets(), KEY_PROPS


def ruff_format(code: str) -> str:
    result = subprocess.run(
        [sys.executable, "-m", "ruff", "format", "--stdin-filename", "example.py", "-"],
        input=code,
        capture_output=True,
        text=True,
        cwd=ROOT,
        check=True,
    )
    return result.stdout


def _format_python(markdown: str) -> str:
    return re.sub(
        r"^```python\n(.*?)^```$",
        lambda m: f"```python\n{ruff_format(m.group(1))}```",
        markdown,
        flags=re.DOTALL | re.MULTILINE,
    )


# ── Generated blocks ────────────────────────────────────────────────────────────────────


def _chart_example(chart: dict[str, Any], rows: list[dict[str, Any]] | None, keys: dict[str, Any]) -> str:
    builder, title = chart["builder"], chart["slug"].replace("-", " ").capitalize()
    args = {k: v for k, v in keys.items() if k not in _LEFT_OUT}
    if chart["slug"] in _SCALAR:
        state = "    percent: int = 72\n"
        call = {"percent": "State.percent", **{k: repr(v) for k, v in _SCALAR[chart["slug"]].items()}}
    else:
        state = "    rows: list[dict] = []\n"
        call = {"data": "State.rows", **{k: repr(v) for k, v in args.items()}}
    call |= {"title": repr(title), "id": repr(chart["slug"])}
    kwargs = ", ".join(f"{k}={v}" for k, v in call.items())
    return (
        f"import reflex as rx\nfrom reflex_silverpoint_react import {builder}\n\n\n"
        f"class State(rx.State):\n{state}\n\n"
        f"def {builder}_view() -> rx.Component:\n    return {builder}({kwargs})\n"
    )


def _family(catalog: dict[str, Any], family: str) -> str:
    datasets, key_props = _demo()
    charts = [c for c in catalog["charts"] if c["family"] == family]
    out = [
        f"**{len(charts)} charts:** " + " · ".join(f"[`{c['builder']}`](#{c['builder']})" for c in charts),
        "",
    ]
    for chart in charts:
        rows = datasets.get(chart["slug"])
        keys = key_props.get(chart["slug"], {})
        out += [f"## {chart['builder']}", "", f"`{chart['slug']}` · `{chart['cls']}` · {chart['summary']}", ""]
        out += ["Its own props (the common ones are in [SKILL.md](../../SKILL.md#common-chart-props)):", ""]
        out += [*_props_table(chart["props"]), ""]
        out += ["```python", _chart_example(chart, rows, keys).rstrip("\n"), "```", ""]
        if rows:
            read = ", ".join(f'{k}="{v}"' for k, v in keys.items() if isinstance(v, str))
            how = f" (read through {read})" if read else " (read through the accessors' defaults)"
            out += [f"The demo's first rows{how}, drawn when `data` is omitted:", ""]
            out += ["```json", json.dumps(rows[:3], ensure_ascii=False), "```", ""]
    return "\n".join(out).rstrip("\n")


def _component_entries(catalog: dict[str, Any], slugs: list[str]) -> str:
    out: list[str] = []
    for slug in slugs:
        entry = next(c for c in catalog["components"] if c["slug"] == slug)
        builder = entry["builder"]
        head = [f"`{slug}`"] + ([f"`{entry['cls']}`"] if entry["cls"] else [])
        out += [f"### {builder}", "", " · ".join(head) + f" · {_summary(getattr(sp, builder))}", ""]
        if entry["positional"]:
            out += ["Positional: " + ", ".join(f"`{name}`" for name in entry["positional"]) + ".", ""]
        out += [*_props_table(entry["props"]), ""]
        if entry["deprecated"]:
            renamed = [
                f"`{old}` → `{new}`" if new else f"`{old}` (ignored)" for old, new in entry["deprecated"].items()
            ]
            out += ["Deprecated, still accepted with a warning or as an alias: " + ", ".join(renamed) + ".", ""]
    return "\n".join(out).rstrip("\n")


def _index(catalog: dict[str, Any]) -> dict[str, Callable[[], str]]:
    families = list(dict.fromkeys(c["family"] for c in catalog["charts"]))

    def chart_index() -> str:
        rows = ["| Family | Reference | Builders |", "|---|---|---|"]
        for family in families:
            names = ", ".join(f"`{c['builder']}`" for c in catalog["charts"] if c["family"] == family)
            path = f"references/charts/{family_slug(family)}.md"
            rows.append(f"| {family} | [{family_slug(family)}.md]({path}) | {names} |")
        return "\n".join(rows)

    def component_index() -> str:
        by_page: dict[str, list[str]] = {}
        for c in catalog["components"]:
            by_page.setdefault(OWN_PAGE.get(c["slug"], "components.md"), []).append(f"`{c['builder']}`")
        rows = ["| Reference | Builders |", "|---|---|"]
        rows += [f"| [{page}](references/{page}) | {', '.join(names)} |" for page, names in by_page.items()]
        return "\n".join(rows)

    def common(kind: str) -> Callable[[], str]:
        return lambda: "\n".join(_props_table(catalog["common"][kind]))

    def helpers() -> str:
        rows = ["| Helper | What it does |", "|---|---|"]
        rows += [f"| `{name}` | {_cell(_summary(getattr(sp, name)))} |" for name in catalog["helpers"]]
        return "\n".join(rows)

    def events() -> str:
        rows = ["| Builder | Events |", "|---|---|"]
        rows.append(
            "| every chart | "
            + ", ".join(f"`{p['name']}`" for p in catalog["common"]["chart"] if p["type"] == "event")
            + " |"
        )
        for entry in [*catalog["charts"], *catalog["components"]]:
            names = [f"`{p['name']}`" for p in entry["props"] if p["type"] == "event" or p["name"].startswith("on_")]
            if names:
                rows.append(f"| `{entry['builder']}` | {', '.join(names)} |")
        return "\n".join(rows)

    def palettes() -> str:
        fields = list(sp.PALETTE_JS_FIELDS)
        rows = ["| Preset | " + " | ".join(f"`{f}`" for f in fields) + " |", "|---|" + "---|" * len(fields)]
        for name, palette in sp.PALETTES.items():
            values = palette.to_dict()
            rows.append(f"| `{name}` | " + " | ".join(f"`{values[f]}`" if f in values else "" for f in fields) + " |")
        return "\n".join(rows)

    components = [c["slug"] for c in catalog["components"] if c["slug"] not in OWN_PAGE]
    return {
        "chart-index": chart_index,
        "component-index": component_index,
        "common-chart-props": common("chart"),
        "common-ui-props": common("ui"),
        "helpers": helpers,
        "events": events,
        "palette-presets": palettes,
        "components": lambda: _component_entries(catalog, components),
        "overlays": lambda: _component_entries(catalog, list(OVERLAYS)),
        "dashboard": lambda: _component_entries(catalog, ["dashboard"]),
        "timeline": lambda: _component_entries(catalog, ["timeline"]),
    }


# ── Assembly ────────────────────────────────────────────────────────────────────────────


def _fill(template: str, catalog: dict[str, Any], blocks: dict[str, Callable[[], str]], source: str) -> str:
    def block(match: re.Match[str]) -> str:
        name = match.group(1)
        if name not in blocks:
            raise ValueError(f"{source}: no generated block named {name}")
        return f"<!-- generated:{name} -->\n\n{blocks[name]()}\n\n<!-- /generated:{name} -->"

    text = template.replace("{{version}}", catalog["version"]).replace("{{wraps}}", catalog["wraps"])
    return re.sub(r"<!-- generated:([a-z-]+) -->", block, text)


def _stamped(markdown: str, catalog: dict[str, Any]) -> str:
    title, _, rest = markdown.partition("\n")
    stamp = f"*Describes reflex-silverpoint-react {catalog['version']}, wrapping silverpoint {catalog['wraps']}.*"
    return f"<!-- {GENERATED} -->\n{title}\n\n{stamp}\n{rest}"


def render(catalog_path: Path = CATALOG) -> dict[str, str]:
    """Every file of the skill, by path under `skills/reflex-silverpoint/`, templates aside."""
    catalog = json.loads(catalog_path.read_text(encoding="utf-8"))
    blocks = _index(catalog)
    files: dict[str, str] = {}

    skill = _fill((TEMPLATES / "SKILL.md").read_text(encoding="utf-8"), catalog, blocks, "SKILL.md")
    end = skill.index("\n---\n", 4) + 5
    files["SKILL.md"] = f"{skill[:end]}\n<!-- {GENERATED} -->\n{skill[end:]}"
    for name in REFERENCES:
        text = _fill((TEMPLATES / f"{name}.md").read_text(encoding="utf-8"), catalog, blocks, f"{name}.md")
        files[f"references/{name}.md"] = _stamped(text, catalog)
    family_template = (TEMPLATES / "chart-family.md").read_text(encoding="utf-8")
    for family in dict.fromkeys(c["family"] for c in catalog["charts"]):
        family_blocks = {**blocks, "family": lambda family=family: _family(catalog, family)}
        text = _fill(family_template.replace("{{family}}", family), catalog, family_blocks, "chart-family.md")
        files[f"references/charts/{family_slug(family)}.md"] = _stamped(text, catalog)
    return {path: _format_python(text).rstrip("\n") + "\n" for path, text in sorted(files.items())}


def extract_examples(files: dict[str, str]) -> list[tuple[str, str]]:
    """Every `python` fence as `(name, code)`; `sh`, `text` and `json` are prose, any other fence fails."""
    found = []
    for path, markdown in files.items():
        base = re.sub(r"[^a-zA-Z0-9]+", "-", path.removesuffix(".md"))
        index = 0
        for match in re.finditer(r"^```([^\n]*)\n(.*?)^```$", markdown, flags=re.DOTALL | re.MULTILINE):
            lang = match.group(1).strip()
            if not lang:
                raise ValueError(f"{path}: a code fence without a language")
            if lang in PROSE:
                continue
            if lang != "python":
                raise ValueError(f"{path}: ```{lang} is neither python nor prose ({', '.join(sorted(PROSE))})")
            index += 1
            found.append((f"{base}-{index}", match.group(2)))
    return found


def main(argv: list[str]) -> int:
    files = render()
    current = {
        str(p.relative_to(SKILL)): p for p in SKILL.rglob("*.md") if "templates" not in p.relative_to(SKILL).parts
    }
    if "--check" in argv:
        stale = sorted(
            set(current) ^ set(files) | {p for p in files if p in current and current[p].read_text() != files[p]}
        )
        for path in stale:
            print(
                f"skills/reflex-silverpoint/{path} is stale: run `uv run python scripts/make_skill.py`", file=sys.stderr
            )
        return 1 if stale else 0
    for path in set(current) - set(files):
        current[path].unlink()
    for path, text in files.items():
        (SKILL / path).parent.mkdir(parents=True, exist_ok=True)
        (SKILL / path).write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
